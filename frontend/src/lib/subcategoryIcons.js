const fallback = pictogram(Compass, "sky");

export function getSubcategoryIcon(group, topic) {
  const items = Object.hasOwn(subcategoryIcons, group) ? subcategoryIcons[group] : null;
  return items && Object.hasOwn(items, topic) ? items[topic] : fallback;
}
